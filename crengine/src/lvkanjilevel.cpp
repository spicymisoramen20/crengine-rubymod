static int kanjiLevelFind(const KanjiLevelEntry * table, int count, lUInt32 cp)
{
    int lo = 0;
    int hi = count - 1;
    while (lo <= hi) {
        int mid = lo + ((hi - lo) >> 1);
        lUInt32 mcp = table[mid].cp;
        if (mcp == cp)
            return (int)table[mid].level;
        if (mcp < cp)
            lo = mid + 1;
        else
            hi = mid - 1;
    }
    return 0;
}

static lString32 jlptLabel(int n)
{
    switch (n) {
    case 1: return lString32("N1");
    case 2: return lString32("N2");
    case 3: return lString32("N3");
    case 4: return lString32("N4");
    case 5: return lString32("N5");
    default: return lString32::empty_str;
    }
}

static lString32 joyoLabel(int g)
{
    switch (g) {
    case 1: return lString32("1");
    case 2: return lString32("2");
    case 3: return lString32("3");
    case 4: return lString32("4");
    case 5: return lString32("5");
    case 6: return lString32("6");
    case 7: {
            // 中
            lString32 s;
            s.append(1, (lChar32)0x4E2D);
            return s;
        }
    default: return lString32::empty_str;
    }
}

static lString32 kankenLabel(int code)
{
    // Fog-friendly short labels; 準 uses U+6E96.
    switch (code) {
    case 1: return lString32("10");
    case 2: return lString32("9");
    case 3: return lString32("8");
    case 4: return lString32("7");
    case 5: return lString32("6");
    case 6: return lString32("5");
    case 7: return lString32("4");
    case 8: return lString32("3");
    case 9: {
            lString32 s;
            s.append(1, (lChar32)0x6E96); // 準
            s.append(1, (lChar32)'2');
            return s;
        }
    case 10: return lString32("2");
    case 11: {
            lString32 s;
            s.append(1, (lChar32)0x6E96); // 準
            s.append(1, (lChar32)'1');
            return s;
        }
    case 12: return lString32("1");
    default: return lString32::empty_str;
    }
}

static bool kanjiLevelIsIdeograph(lUInt32 cp)
{
    // CJK Unified + Ext A (enough for EPUB body text); skip kana/latin.
    if (cp >= 0x3400 && cp <= 0x4DBF)
        return true;
    if (cp >= 0x4E00 && cp <= 0x9FFF)
        return true;
    if (cp >= 0xF900 && cp <= 0xFAFF)
        return true;
    return false;
}

void kanjiLevelLabelsForText(const lString32 & text, int scheme,
        LVArray<lString32> & out)
{
    out.clear();
    if (scheme == RUBY_TOGGLE_LEVEL_OFF || text.empty())
        return;

    for (int i = 0; i < text.length(); i++) {
        lUInt32 cp = (lUInt32)text[i];
        if (!kanjiLevelIsIdeograph(cp))
            continue;
        lString32 label;
        if (scheme == RUBY_TOGGLE_LEVEL_JLPT) {
            int n = kanjiLevelFind(s_jlpt, s_jlpt_count, cp);
            label = jlptLabel(n);
        } else if (scheme == RUBY_TOGGLE_LEVEL_JOYO) {
            int g = kanjiLevelFind(s_joyo, s_joyo_count, cp);
            label = joyoLabel(g);
        } else if (scheme == RUBY_TOGGLE_LEVEL_KANKEN) {
            int k = kanjiLevelFind(s_kanken, s_kanken_count, cp);
            label = kankenLabel(k);
        }
        out.add(label); // may be empty when unmapped
    }
}

lString32 kanjiLevelLabelForText(const lString32 & text, int scheme)
{
    LVArray<lString32> labels;
    kanjiLevelLabelsForText(text, scheme, labels);
    // Backward-compat: hardest among mapped (JLPT low N / Joyo high / Kanken hard).
    lString32 best;
    int best_rank = 0; // JLPT: 6-n so N1 wins; Joyo: grade as-is
    for (int i = 0; i < labels.length(); i++) {
        if (labels[i].empty())
            continue;
        int rank = 0;
        if (scheme == RUBY_TOGGLE_LEVEL_JLPT) {
            // "N1".."N5"
            if (labels[i].length() >= 2)
                rank = 6 - (labels[i][1] - '0');
        } else if (scheme == RUBY_TOGGLE_LEVEL_JOYO) {
            if (labels[i].length() == 1 && labels[i][0] == 0x4E2D)
                rank = 7;
            else if (labels[i].length() == 1 && labels[i][0] >= '1'
                    && labels[i][0] <= '6')
                rank = labels[i][0] - '0';
        } else if (scheme == RUBY_TOGGLE_LEVEL_KANKEN) {
            // Harder 級 => higher rank. Re-derive from label text.
            const lString32 & lb = labels[i];
            if (lb.length() == 2 && lb[0] == 0x6E96 && lb[1] == '2')
                rank = 9; // 準2
            else if (lb.length() == 2 && lb[0] == 0x6E96 && lb[1] == '1')
                rank = 11; // 準1
            else if (lb.length() == 2 && lb[0] == '1' && lb[1] == '0')
                rank = 1; // 10
            else if (lb.length() == 1 && lb[0] >= '1' && lb[0] <= '9') {
                // "9".."1" map to codes 2..12 via reverse of kankenLabel
                // 9->2, 8->3, ..., 3->8, 2->10, 1->12
                int d = lb[0] - '0';
                if (d == 1)
                    rank = 12;
                else if (d == 2)
                    rank = 10;
                else if (d >= 3 && d <= 9)
                    rank = 11 - d; // 9->2 ... 3->8
            }
        }
        if (rank > best_rank) {
            best_rank = rank;
            best = labels[i];
        }
    }
    return best;
}
